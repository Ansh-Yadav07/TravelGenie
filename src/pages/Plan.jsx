import { useMemo } from 'react';
import { useLocation, useSearchParams } from 'react-router-dom';
import { Check, Info } from 'lucide-react';
import PlannerForm from '../components/home/PlannerForm';
import { getTrip } from '../lib/storage';

const WHAT_YOU_GET = [
  'A day-by-day plan with real, named places',
  'Stays that fit your budget (multi-day trips)',
  'Ways to get there and around, with costs',
  'Google Maps links and local tips',
];

const int = (v) => {
  const n = parseInt(v, 10);
  return Number.isFinite(n) ? n : undefined;
};

/** Build the planner's initial request from the URL (?edit= or deep-link params). */
function requestFromParams(params) {
  const editId = params.get('edit');
  if (editId) {
    const trip = getTrip(editId);
    return { editing: trip ? trip.request : null, editMissing: !trip, initial: trip?.request };
  }
  const initial = {};
  const destination = params.get('destination');
  if (destination) initial.destination = destination.slice(0, 80);
  const days = int(params.get('days'));
  if (days) Object.assign(initial, { plan_mode: 'days', duration: days });
  const travelers = int(params.get('travelers'));
  if (travelers) {
    initial.travelers = travelers;
    if (travelers === 1) initial.companions = 'solo';
    else if (travelers === 2) initial.companions = 'couple';
  }
  if (params.get('budget')) initial.budget = params.get('budget');
  if (params.get('mood')) initial.mood = params.get('mood');
  return { editing: null, editMissing: false, initial };
}

export default function Plan() {
  const [params] = useSearchParams();
  const { search } = useLocation();
  const { editing, editMissing, initial } = useMemo(() => requestFromParams(params), [params]);

  return (
    <div className="page-top pb-24 md:pb-32" style={{ background: 'var(--bg-grouped)' }}>
      <div className="container-x">
        <header className="mb-10 md:mb-12 max-w-[640px]">
          <h1 className="t-display">{editing ? 'Edit your trip' : 'Plan a trip'}</h1>
          <p className="t-body t-secondary mt-3">
            {editing
              ? `Change anything and Gemini will plan ${editing.destination || 'it'} again. Your original plan stays saved.`
              : 'Tell us the basics and the style you like. Gemini builds a day-by-day plan with real places, stays and costs.'}
          </p>
          {editMissing && (
            <p className="mt-4 inline-flex items-start gap-2 t-subhead rounded-[12px] px-3.5 py-2.5" style={{ background: 'var(--orange-soft)', color: 'var(--orange-text)' }}>
              <Info size={17} strokeWidth={2} aria-hidden className="mt-0.5 shrink-0" />
              That trip isn’t saved on this device any more, so we’ve started a new plan.
            </p>
          )}
        </header>

        <PlannerForm
          key={search}
          variant="page"
          autoFocus={!initial?.destination}
          initialRequest={initial}
          aside={<WhatYouGet />}
        />
      </div>
    </div>
  );
}

function WhatYouGet() {
  return (
    <div className="card-flat p-6" style={{ background: 'transparent' }}>
      <h2 className="t-headline">What you’ll get</h2>
      <ul className="mt-4 space-y-3">
        {WHAT_YOU_GET.map((item) => (
          <li key={item} className="flex items-start gap-3 t-subhead">
            <span className="mt-0.5 w-5 h-5 shrink-0 rounded-full flex items-center justify-center" style={{ background: 'var(--green-soft)', color: 'var(--green-text)' }}>
              <Check size={13} strokeWidth={2.75} aria-hidden />
            </span>
            <span className="t-secondary">{item}</span>
          </li>
        ))}
      </ul>
      <p className="t-caption t-tertiary mt-5">Plans are generated by Google Gemini. Check prices and opening hours before you book.</p>
    </div>
  );
}
